    def think(self, query: str) -> BrainDecision:

        if not isinstance(query, str):
            raise TypeError("Query must be a string.")

        query = query.strip()

        if not query:
            raise ValueError("Query cannot be empty.")

        understanding = self.understand(query)

        agents = self.select_agents(understanding)

        reasoning = self.generate_reasoning(
            understanding,
            agents
        )

        confidence = self.calculate_confidence(
            understanding,
            agents
        )

        return BrainDecision(
            understanding=understanding,
            recommended_agents=agents,
            reasoning=reasoning,
            confidence=confidence
        )


    def understand(self, query: str) -> QueryUnderstanding:

        normalized_query = self.normalize(query)

        intent = self.detect_intent(normalized_query)

        goal = self.extract_goal(query)

        entities = self.extract_entities(normalized_query)

        requirements = self.extract_requirements(
            normalized_query
        )

        capabilities = self.detect_capabilities(
            normalized_query
        )

        constraints = self.extract_constraints(
            normalized_query
        )

        complexity = self.calculate_complexity(
            normalized_query,
            requirements,
            capabilities
        )

        needs_tools = self.detect_tool_requirement(
            normalized_query
        )

        needs_multiple_agents = (
            len(capabilities) >= 2
            or len(requirements) >= 2
            or complexity >= 0.60
        )

        return QueryUnderstanding(

            original_query=query,

            intent=intent,

            goal=goal,

            complexity=complexity,

            entities=entities,

            requirements=requirements,

            constraints=constraints,

            capabilities=capabilities,

            needs_tools=needs_tools,

            needs_multiple_agents=needs_multiple_agents
        )


    def normalize(self, query: str) -> str:

        query = query.lower().strip()


        query = re.sub(
            r"\s+",
            " ",
            query
        )

        return query



    def detect_intent(self, query: str) -> str:

        scores = {}

        for intent, signals in self.intent_signals.items():

            score = 0

            for signal in signals:

                if self.signal_matches(
                    query,
                    signal
                ):
                    score += self.signal_weight(
                        signal
                    )

            scores[intent] = score


        if (
            "machine learning" in query
            or "ml model" in query
            or "machine-learning" in query
        ):
            scores["MACHINE_LEARNING"] += 3

        if (
            "research" in query
            or "latest" in query
            or "recent" in query
        ):
            scores["RESEARCH"] += 2


        if max(scores.values()) == 0:
            return "GENERAL"

        best_intent = max(
            scores,
            key=scores.get
        )

        return best_intent


    def signal_matches(
        self,
        query: str,
        signal: str
    ) -> bool:

        if " " in signal:
            return signal in query


        return bool(
            re.search(
                rf"\b{re.escape(signal)}\b",
                query
            )
        )

    def signal_weight(
        self,
        signal: str
    ) -> float:

        strong_signals = {

            "machine learning": 3.0,
            "machine-learning": 3.0,
            "ml model": 3.0,

            "data analysis": 3.0,

            "deep learning": 3.0,

            "research": 3.0,

            "debug": 2.5,

            "classification": 2.0,
            "regression": 2.0,

            "dataset": 1.5,

            "python": 1.5
        }

        return strong_signals.get(
            signal,
            1.0
        )

    def extract_goal(
        self,
        query: str
    ) -> str:

        patterns = [

            r"i want to (.+)",

            r"i need to (.+)",

            r"help me (.+)",

            r"how can i (.+)",

            r"how do i (.+)",

            r"can you (.+)",

            r"please (.+)"
        ]

        normalized = self.normalize(query)

        for pattern in patterns:

            match = re.search(
                pattern,
                normalized
            )

            if match:
                return match.group(1).strip()

        return query.strip()


    def extract_entities(
        self,
        query: str
    ) -> List[str]:

        entities = []

        for entity in self.known_entities:

            if self.signal_matches(
                query,
                entity
            ):
                entities.append(entity)

        return sorted(
            set(entities)
        )


    def extract_requirements(
        self,
        query: str
    ) -> List[str]:

        requirements = []

        for requirement, signals in (
            self.requirement_signals.items()
        ):

            for signal in signals:

                if self.signal_matches(
                    query,
                    signal
                ):

                    requirements.append(
                        requirement
                    )

                    break

        return requirements

    def detect_capabilities(
        self,
        query: str
    ) -> List[str]:

        capabilities = []

        for capability, signals in (
            self.intent_signals.items()
        ):

            matched = False

            for signal in signals:

                if self.signal_matches(
                    query,
                    signal
                ):
                    matched = True
                    break

            if matched:
                capabilities.append(
                    capability
                )

        return capabilities

    def extract_constraints(
        self,
        query: str
    ) -> List[str]:

        constraints = []

        patterns = [

            r"under\s+(\d+)",

            r"within\s+(\d+)",

            r"before\s+(.+)",

            r"after\s+(.+)",

            r"only\s+(.+)",

            r"without\s+(.+)",

            r"using\s+(.+)"
        ]

        for pattern in patterns:

            matches = re.findall(
                pattern,
                query
            )

            for match in matches:

                constraints.append(
                    str(match).strip()
                )

        return constraints


    def calculate_complexity(
        self,
        query: str,
        requirements: List[str],
        capabilities: List[str]
    ) -> float:

        score = 0.20

        words = query.split()


        if len(words) > 12:
            score += 0.10

        if len(words) > 25:
            score += 0.10


        if len(requirements) >= 2:
            score += 0.15

        if len(requirements) >= 3:
            score += 0.10


        if len(capabilities) >= 2:
            score += 0.10

        if len(capabilities) >= 3:
            score += 0.10


        multi_step_signals = [
            "and",
            "then",
            "after",
            "also",
            "first",
            "finally",
            "step"
        ]

        matches = sum(
            1
            for word in multi_step_signals
            if self.signal_matches(
                query,
                word
            )
        )

        score += min(
            matches * 0.05,
            0.15
        )


        if (
            "MACHINE_LEARNING" in capabilities
            and "optimization" in requirements
        ):
            score += 0.10

        return round(
            min(score, 1.0),
            2
        )


