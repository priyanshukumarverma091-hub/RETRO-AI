    def select_agents(
        self,
        understanding: QueryUnderstanding
    ) -> List[str]:

        agents = []

        intent = understanding.intent

        requirements = (
            understanding.requirements
        )



        intent_agent_map = {

            "MACHINE_LEARNING":
                "MLAgent",

            "DATA_ANALYSIS":
                "DataAnalysisAgent",

            "CODING":
                "CodingAgent",

            "RESEARCH":
                "ResearchAgent",

            "REASONING":
                "ReasoningAgent"
        }

        primary_agent = intent_agent_map.get(
            intent
        )

        if primary_agent:
            agents.append(
                primary_agent
            )


        if "implementation" in requirements:

            if "CodingAgent" not in agents:

                agents.append(
                    "CodingAgent"
                )

        if "analysis" in requirements:

            if "DataAnalysisAgent" not in agents:

                agents.append(
                    "DataAnalysisAgent"
                )

        if "research" in requirements:

            if "ResearchAgent" not in agents:

                agents.append(
                    "ResearchAgent"
                )

        if "debugging" in requirements:

            if "CodingAgent" not in agents:

                agents.append(
                    "CodingAgent"
                )

        if (
            "explanation" in requirements
            or "comparison" in requirements
        ):

            if "ReasoningAgent" not in agents:

                agents.append(
                    "ReasoningAgent"
                )


        if "prediction" in requirements:

            if "MLAgent" not in agents:

                agents.append(
                    "MLAgent"
                )


        if understanding.complexity >= 0.60:

            agents.append(
                "CriticAgent"
            )


        if not agents:

            agents.append(
                "GeneralAgent"
            )

        # Remove duplicates
        return list(
            dict.fromkeys(agents)
        )


    def generate_reasoning(
        self,
        understanding: QueryUnderstanding,
        agents: List[str]
    ) -> List[str]:

        reasoning = []

        reasoning.append(
            f"Intent detected: "
            f"{understanding.intent}"
        )

        reasoning.append(
            f"Goal identified: "
            f"{understanding.goal}"
        )

        reasoning.append(
            f"Complexity score: "
            f"{understanding.complexity}"
        )

        if understanding.capabilities:

            reasoning.append(
                "Capabilities detected: "
                + ", ".join(
                    understanding.capabilities
                )
            )

        if understanding.requirements:

            reasoning.append(
                "Requirements detected: "
                + ", ".join(
                    understanding.requirements
                )
            )

        if understanding.entities:

            reasoning.append(
                "Entities detected: "
                + ", ".join(
                    understanding.entities
                )
            )

        reasoning.append(
            "Selected agents: "
            + ", ".join(agents)
        )

        if understanding.needs_tools:

            reasoning.append(
                "External tools may be required."
            )

        if understanding.needs_multiple_agents:

            reasoning.append(
                "Task requires coordinated "
                "multi-agent processing."
            )

        return reasoning


    def calculate_confidence(
        self,
        understanding: QueryUnderstanding,
        agents: List[str]
    ) -> float:

        confidence = 0.45


        if understanding.intent != "GENERAL":

            confidence += 0.20


        if understanding.requirements:

            confidence += 0.10

        if understanding.entities:

            confidence += 0.05


        if understanding.capabilities:

            confidence += 0.05


        if agents:

            confidence += 0.05

        # Multiple independent signals
        if len(
            understanding.capabilities
        ) >= 2:

            confidence += 0.05

        return round(
            min(confidence, 0.95),
            2
        )



